"""goAML XML export (UNODC structure) and CTR (FinCEN Form 112) drafting.

goAML is the UNODC reporting platform used by many FIUs. There is no single global
schema: each FIU publishes its own XSD and validates against it. This exporter produces a
*structurally faithful* report node set that can be adapted to a national schema, and it
says so in the header rather than pretending to be submission-ready.

CTR drafting is included because a structuring investigation almost always needs one for
the transactions that crossed the threshold legitimately.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import date, timedelta
from decimal import Decimal
from xml.sax.saxutils import escape

from anjali.core.models import SARReport, Transaction
from anjali.core.util import money, today

HEADER = "<!-- Generated by ANJALI-AI. Validate against your FIU's goAML XSD before submission. -->"


def _el(name: str, value: object | None, indent: int = 0) -> str:
    pad = "  " * indent
    if value is None or value == "":
        return f"{pad}<{name}/>"
    return f"{pad}<{name}>{escape(str(value))}</{name}>"


def _person(subject, indent: int) -> str:
    pad = "  " * indent
    lines = [f"{pad}<entity>"]
    lines.append(_el("name", subject.name, indent + 1))
    if subject.dob:
        lines.append(f"{pad}  <birthdate>{escape(subject.dob)}</birthdate>")
    if subject.country:
        lines.append(f"{pad}  <country>{escape(subject.country)}</country>")
    lines.append(_el("entity_type", subject.entity_type, indent + 1))
    lines.append(_el("role", subject.role, indent + 1))
    for key, value in subject.identifiers.items():
        lines.append(f"{pad}  <identifier>")
        lines.append(_el("type", key, indent + 2))
        lines.append(_el("number", value, indent + 2))
        lines.append(f"{pad}  </identifier>")
    lines.append(f"{pad}</entity>")
    return "\n".join(lines)


def to_goaml(report: SARReport, transactions: Sequence[Transaction] = ()) -> str:
    lines = [HEADER]
    lines.append("<report>")
    lines.append(_el("rentity_id", "ANJALI", 1))
    lines.append(_el("submission_code", "E", 1))
    lines.append(_el("report_code", "STR" if report.jurisdiction.value != "US" else "SAR", 1))
    lines.append(_el("entity_reference", report.report_id, 1))
    lines.append(_el("fiu_ref_number", "", 1))
    lines.append(_el("submission_date", today().isoformat(), 1))
    lines.append(_el("currency_code", report.currency, 1))

    lines.append("  <location>")
    lines.append(_el("country", report.jurisdiction.value if report.jurisdiction.value != "INTL" else "", 2))
    lines.append("  </location>")

    lines.append("  <report_parties>")
    for subject in report.subjects:
        lines.append(_person(subject, 2))
    lines.append("  </report_parties>")

    lines.append(_el("reason", ", ".join(report.typologies), 1))
    lines.append(_el("action", "Reported to FIU", 1))

    lines.append("  <activity>")
    if report.activity_start:
        lines.append(_el("date_from", report.activity_start.isoformat(), 2))
    if report.activity_end:
        lines.append(_el("date_to", report.activity_end.isoformat(), 2))
    lines.append("  </activity>")

    lines.append("  <transactions>")
    for txn in transactions[:500]:
        lines.append("    <transaction>")
        lines.append(_el("transactionnumber", txn.txn_id, 3))
        lines.append(_el("date_transaction", txn.timestamp.date().isoformat(), 3))
        lines.append(_el("amount_local", f"{txn.amount:.2f}", 3))
        lines.append(_el("transaction_type", txn.txn_type, 3))
        lines.append(_el("direction", txn.direction.value, 3))
        if txn.from_account:
            lines.append(_el("from_account", txn.from_account, 3))
        if txn.to_account:
            lines.append(_el("to_account", txn.to_account, 3))
        if txn.country_from:
            lines.append(_el("country_from", txn.country_from, 3))
        if txn.country_to:
            lines.append(_el("country_to", txn.country_to, 3))
        lines.append("    </transaction>")
    lines.append("  </transactions>")

    lines.append("  <report_indicators>")
    for typology in report.typologies:
        lines.append(_el("indicator", typology.replace("_", " ").upper(), 2))
    lines.append("  </report_indicators>")

    lines.append("  <suspicion_details>")
    lines.append(_el("narrative", report.narrative, 2))
    lines.append("  </suspicion_details>")

    if report.citations:
        lines.append("  <regulatory_basis>")
        for cit in report.citations:
            lines.append("    <provision>")
            lines.append(_el("citation", cit.citation, 3))
            lines.append(_el("title", cit.title, 3))
            lines.append("    </provision>")
        lines.append("  </regulatory_basis>")

    lines.append("</report>")
    return "\n".join(lines)


