# CTR (FinCEN Form 112)
# --------------------------------------------------------------------------- #
def build_ctr(
    transactions: Sequence[Transaction],
    *,
    threshold: Decimal = Decimal("10000"),
) -> dict[str, object]:
    """Aggregate currency transactions per party/business day above the threshold."""
    groups: dict[tuple[str, str], list[Transaction]] = {}
    for txn in transactions:
        if (txn.txn_type or "").lower() not in {"cash_deposit", "cash_withdrawal", "cash"}:
            continue
        # Attribute the cash to the institution's own account: on a deposit that is the
        # receiving account, on a withdrawal it is the account being debited (the payee
        # on a withdrawal is a merchant, not the party being reported).
        if txn.direction.value == "credit":
            party = txn.to_account or txn.from_account or "unknown"
        else:
            party = txn.from_account or txn.to_account or "unknown"
        key = (party, txn.timestamp.date().isoformat())
        groups.setdefault(key, []).append(txn)

    filings = []
    for (party, day), txns in sorted(groups.items()):
        cash_in = money(sum(t.amount for t in txns if t.direction.value == "credit"))
        cash_out = money(sum(t.amount for t in txns if t.direction.value == "debit"))
        if cash_in <= threshold and cash_out <= threshold:
            continue
        filings.append(
            {
                "account": party,
                "business_day": day,
                "cash_in": str(cash_in),
                "cash_out": str(cash_out),
                "transaction_count": len(txns),
                "txn_ids": [t.txn_id for t in txns],
                "branches": sorted({t.branch for t in txns if t.branch}),
                "reportable": True,
                "form": "FinCEN Form 112 (CTR)",
                "due_date": (date.fromisoformat(day) + timedelta(days=15)).isoformat(),
            }
        )
    return {
        "threshold": str(threshold),
        "filings": filings,
        "count": len(filings),
        "method": (
            "Cash in and cash out are aggregated separately per account and business day, as "
            "required by 31 CFR 1010.311 and 1010.313. Nothing in this output is filed "
            "automatically."
        ),
    }


def ctr_to_markdown(payload: dict[str, object]) -> str:
    lines = ["# Currency Transaction Report (CTR) worksheet", ""]
    lines.append(f"Threshold: {payload['threshold']} — {payload['count']} required filing(s).")
    lines.append("")
    if not payload["filings"]:
        lines.append("_No currency activity above the threshold was found in this dataset._")
        return "\n".join(lines)
    lines.append("| Account | Business day | Cash in | Cash out | Txns | Branches | Due |")
    lines.append("|---------|--------------|---------|----------|------|----------|-----|")
    for filing in payload["filings"]:  # type: ignore[union-attr]
        lines.append(
            f"| {filing['account']} | {filing['business_day']} | {filing['cash_in']} | "
            f"{filing['cash_out']} | {filing['transaction_count']} | "
            f"{', '.join(filing['branches']) or '—'} | {filing['due_date']} |"
        )
    lines.append("")
    lines.append(f"_{payload['method']}_")
    return "\n".join(lines)
